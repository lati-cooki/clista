#!/usr/bin/env node
// Generate the cockpit's example-mirror registry (worker/examples/) from the
// in-repo protocol package. DE-VENDORED 2026-07-12 (monorepo cutover item 3):
// this replaces scripts/vendor-examples.mjs. The output is BUILD ARTIFACT, not
// source — worker/examples/ is gitignored and regenerated before every test,
// build, and dev run (pre* hooks in package.json), so there is no committed
// copy to drift and no --check mode to run. The source of truth is
// packages/protocol/examples/manifest.json; adding an example to the cockpit
// is adding a manifest entry there — never editing the cockpit.
//
// Every published entry is re-verified with the SAME engine the app ships
// (validate per thread; verifyCrossThreadProvenance for cross-thread examples)
// and generation refuses if anything fails — a broken example cannot ship.
import { writeFileSync, existsSync, mkdirSync, rmSync } from "node:fs";
import { readFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");
const outDir = join(repoRoot, "worker", "examples");
// The in-repo protocol package — the same one worker/engine/index.js imports.
const protocolDir = resolve(repoRoot, "..", "packages", "protocol");

const fail = (code, msg) => {
  console.error(`\n✘ ${msg}`);
  process.exit(code);
};

const manifestPath = join(protocolDir, "examples", "manifest.json");
if (!existsSync(manifestPath)) {
  fail(3, `No examples/manifest.json at ${protocolDir} — is this checkout the full monorepo?`);
}

const requireProtocol = createRequire(join(protocolDir, "package.json"));
const { readEventsAt } = requireProtocol("./src/events.js");
const { validateEvents } = requireProtocol("./src/validator.js");
const { verifyCrossThreadProvenance } = requireProtocol("./src/provenance.js");

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
if (manifest.version !== "clista.examples.manifest.v0") {
  fail(2, `Unsupported manifest version ${manifest.version}`);
}
const published = (manifest.examples || []).filter((e) => e.published);
if (published.length === 0) {
  fail(2, "manifest has no published examples");
}

const safeIdent = (id) => "ex_" + id.replace(/[^A-Za-z0-9]+/g, "_");
const built = [];

for (const ex of published) {
  const threads = [];
  for (const t of ex.threads) {
    const file = join(protocolDir, t.file);
    if (!existsSync(file)) fail(2, `example ${ex.id}: missing file ${t.file}`);
    const events = readEventsAt(file);
    if (!events.length) fail(2, `example ${ex.id}: ${t.file} is empty`);
    const result = validateEvents(events);
    if (!result.valid) fail(2, `example ${ex.id}: ${t.file} failed validate: ${JSON.stringify(result.errors)}`);
    if (!events.every((e) => e.thread_id === t.threadId)) {
      fail(2, `example ${ex.id}: ${t.file} contains events outside thread ${t.threadId}`);
    }
    threads.push({ role: t.role, threadId: t.threadId, events });
  }
  if (!threads.some((t) => t.threadId === ex.entryThreadId)) {
    fail(2, `example ${ex.id}: entryThreadId ${ex.entryThreadId} not among declared threads`);
  }
  if (ex.verifyCrossThread) {
    const parent = threads.find((t) => t.role === "parent");
    const arms = threads.filter((t) => t.role === "arm");
    if (!parent || arms.length === 0) fail(2, `example ${ex.id}: verifyCrossThread needs one parent + >=1 arm`);
    const report = verifyCrossThreadProvenance(parent.events, arms.map((a) => a.events));
    if (!report.valid || report.summary.verified < 1) {
      fail(2, `example ${ex.id}: cross-thread provenance failed: ${JSON.stringify(report.summary)}`);
    }
  }
  built.push({
    id: ex.id,
    title: ex.title,
    summary: ex.summary,
    kind: ex.kind,
    domain: ex.domain || null,
    entryThreadId: ex.entryThreadId,
    threads,
  });
}

// Render generated modules deterministically (same manifest+files => same bytes).
function moduleFor(ex) {
  return (
    `// Generated from packages/protocol examples/manifest.json entry "${ex.id}".\n` +
    `// Build artifact — gitignored, regenerated by scripts/generate-examples.mjs.\n` +
    `export const example = ${JSON.stringify(ex, null, 2)};\n`
  );
}
function indexModule(exs) {
  const imports = exs.map((e) => `import { example as ${safeIdent(e.id)} } from "./${e.id}.js";`).join("\n");
  const list = exs.map((e) => `  ${safeIdent(e.id)},`).join("\n");
  return (
    `// Generated by scripts/generate-examples.mjs — build artifact, gitignored.\n` +
    `// The cockpit's example-mirror registry, from packages/protocol.\n` +
    `${imports}\n\nexport const examples = [\n${list}\n];\n`
  );
}

// Regenerate the directory from scratch so removed examples don't linger.
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
for (const ex of built) writeFileSync(join(outDir, `${ex.id}.js`), moduleFor(ex), "utf8");
writeFileSync(join(outDir, "index.js"), indexModule(built), "utf8");

console.log(`Generated ${built.length} example(s) into worker/examples/ from packages/protocol:`);
for (const ex of built) {
  const total = ex.threads.reduce((n, t) => n + t.events.length, 0);
  console.log(`  ${ex.id}  (${ex.threads.length} thread(s), ${total} events)`);
}
